function seed(id, nombre, categoria, notas = '') {
  return { id: `seed_${id}`, nombre, categoria, notas }
}

function bloque(categoria, filas) {
  return filas.map(([id, nombre, notas = '']) => seed(id, nombre, categoria, notas))
}

